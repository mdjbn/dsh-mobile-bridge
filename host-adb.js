/**
 * Optional host-side adb routing.
 *
 * The Android tools that ship with the `@zseven-w/dsh-android` bundle run
 * `adb` **on this server**, but the phone is attached to the PC. adb has no
 * notion of where the server lives, so the fix is the documented one: point a
 * local adb *client* at the adb *server* the PC bridge is already running,
 * with `ADB_SERVER_SOCKET=tcp:<pc>:5037`.
 *
 * `dsh-android` resolves its binary once, when its plugin is applied, in this
 * order: the `ADB` env var → `adb` on PATH → `$HOME/Android/Sdk/platform-tools/adb`.
 * This module therefore installs into that last location (which needs no env
 * var and no restart ordering) and additionally exports the env vars so a
 * reload picks the routing up immediately.
 *
 * @module dsh-pc-mobile-bridge/host-adb
 */

import { execFile } from 'node:child_process'
import { createWriteStream } from 'node:fs'
import { chmod, mkdir, rename, rm, stat, writeFile, readFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { dirname, isAbsolute, join, resolve } from 'node:path'
import { Readable } from 'node:stream'
import { pipeline } from 'node:stream/promises'
import { promisify } from 'node:util'

const run = promisify(execFile)

const WRAPPER_MARKER = '# generated by dsh-pc-mobile-bridge'

/** Resolve the configured SDK root, expanding a leading `~` and relative paths. */
export function resolveSdkRoot(config) {
  const configured = typeof config.hostSdkPath === 'string' ? config.hostSdkPath.trim() : ''
  const base = configured === '' ? 'Android/Sdk' : configured
  if (base.startsWith('~')) return resolve(homedir(), base.replace(/^~\/?/, ''))
  return isAbsolute(base) ? base : resolve(homedir(), base)
}

async function exists(path) {
  try {
    await stat(path)
    return true
  } catch {
    return false
  }
}

/** Download `url` to `destination`, streaming so a 15 MiB archive never sits in memory. */
async function download(url, destination) {
  const response = await fetch(url, { redirect: 'follow' })
  if (!response.ok || response.body === null) {
    throw new Error(`download failed: HTTP ${response.status} ${response.statusText} for ${url}`)
  }
  await mkdir(dirname(destination), { recursive: true })
  await pipeline(Readable.fromWeb(response.body), createWriteStream(destination))
  const size = (await stat(destination)).size
  if (size < 1024 * 1024) throw new Error(`download looks truncated: ${size} bytes from ${url}`)
  return size
}

/** Extract a zip through the system `unzip`; there is no zip reader in core Node. */
async function extractZip(archive, destination) {
  await mkdir(destination, { recursive: true })
  try {
    await run('unzip', ['-oq', archive, '-d', destination], { maxBuffer: 16 * 1024 * 1024 })
  } catch (error) {
    if (error?.code === 'ENOENT') {
      throw new Error('the `unzip` command is not installed on this server — install it or copy a '
        + 'platform-tools directory to the PC bridge and skip install_host_adb')
    }
    throw new Error(`unzip failed: ${error?.stderr?.toString?.().trim() || error?.message || error}`)
  }
}

/** The wrapper script content: pin ADB_SERVER_SOCKET, then exec the real client. */
function wrapperScript(realAdb, host, port) {
  return `#!/bin/sh
${WRAPPER_MARKER}
# Routes every adb call made on this DSH server to the adb server running on
# the Windows PC, which owns the USB port the phone is attached to.
exec env ADB_SERVER_SOCKET="tcp:${host}:${port}" "${realAdb}" "$@"
`
}

/** Report what routing is currently in place, without changing anything. */
export async function hostAdbStatus(config) {
  const sdkRoot = resolveSdkRoot(config)
  const wrapper = join(sdkRoot, 'platform-tools', 'adb')
  const realAdb = join(sdkRoot, '.dsh-real-platform-tools', 'adb')
  let wrapperContent
  try {
    wrapperContent = await readFile(wrapper, 'utf8')
  } catch {
    wrapperContent = undefined
  }
  return {
    sdkRoot,
    wrapperPath: wrapper,
    wrapperInstalled: wrapperContent?.includes(WRAPPER_MARKER) === true,
    foreignFileAtWrapperPath: wrapperContent !== undefined && !wrapperContent.includes(WRAPPER_MARKER),
    realAdbPath: realAdb,
    realAdbPresent: await exists(realAdb),
    envAdb: process.env.ADB ?? null,
    envAdbServerSocket: process.env.ADB_SERVER_SOCKET ?? null,
  }
}

/**
 * Install a routed adb client for this server.
 *
 * `host`/`port` describe the PC bridge's adb server. When `clientPath` already
 * points at a usable adb binary it is reused instead of downloading one.
 */
export async function installHostAdb(config, { host, port, force = false, clientPath }) {
  if (typeof host !== 'string' || host.trim() === '') {
    throw new Error('install_host_adb needs the PC LAN address — the bridge URL in the plugin config provides it')
  }
  const sdkRoot = resolveSdkRoot(config)
  const realDir = join(sdkRoot, '.dsh-real-platform-tools')
  const realAdb = join(realDir, 'adb')
  const wrapperDir = join(sdkRoot, 'platform-tools')
  const wrapper = join(wrapperDir, 'adb')
  const steps = []

  let source = typeof clientPath === 'string' && clientPath.trim() !== '' ? clientPath.trim() : ''
  if (source === '' && !force && await exists(realAdb)) {
    source = realAdb
    steps.push(`reused the existing client at ${realAdb}`)
  }
  if (source === '' || force === true) {
    const archive = join(sdkRoot, '.dsh-platform-tools-linux.zip')
    const bytes = await download(config.platformToolsUrl, archive)
    steps.push(`downloaded ${config.platformToolsUrl} (${bytes} bytes)`)
    const staging = join(sdkRoot, '.dsh-extract')
    await rm(staging, { recursive: true, force: true })
    await extractZip(archive, staging)
    await rm(realDir, { recursive: true, force: true })
    await mkdir(dirname(realDir), { recursive: true })
    await rename(join(staging, 'platform-tools'), realDir)
    await rm(staging, { recursive: true, force: true })
    await rm(archive, { force: true })
    source = realAdb
    steps.push(`extracted platform-tools to ${realDir}`)
  }

  await mkdir(wrapperDir, { recursive: true })
  await writeFile(wrapper, wrapperScript(source, host.trim(), String(port)), 'utf8')
  await chmod(wrapper, 0o755)
  steps.push(`wrote the routed wrapper to ${wrapper}`)

  // Export for the running DSH process too: harmless when this plugin is
  // applied after dsh-android, and enough to activate routing when it is not.
  process.env.ADB = wrapper
  process.env.ADB_SERVER_SOCKET = `tcp:${host.trim()}:${String(port)}`
  steps.push('exported ADB and ADB_SERVER_SOCKET into the running DSH process')

  let probe
  try {
    const { stdout, stderr } = await run(wrapper, ['devices', '-l'], { timeout: 20_000 })
    probe = { ok: true, output: `${stdout}${stderr}`.trim() }
  } catch (error) {
    probe = { ok: false, error: `${error?.stderr?.toString?.().trim() || error?.message || error}` }
  }
  steps.push(probe.ok
    ? 'verified: the routed adb client answered `adb devices -l`'
    : 'the routed adb client could NOT reach the PC adb server — check that dsh-mobile-bridge.exe is running '
      + 'with its adb server started and that this server can reach the PC LAN address')

  return {
    host: host.trim(),
    port,
    sdkRoot,
    wrapperPath: wrapper,
    clientPath: source,
    env: { ADB: wrapper, ADB_SERVER_SOCKET: `tcp:${host.trim()}:${String(port)}` },
    probe,
    steps,
    nextStep: 'dsh-android resolves adb when its plugin is applied, so restart DSH (or reload the profile) '
      + 'for android_* tools to use this routing.',
  }
}
